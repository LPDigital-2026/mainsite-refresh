#!/usr/bin/env python3
"""Regenerate lilypawdigital/inc/pages/known-fingerprints.php.

Run from the repository root after changing anything in
lilypawdigital/inc/pages/*.html, then commit the result. It fingerprints
every version of the page content in the git history (and the working
tree), so the theme can recognise a page nobody has edited by hand and
update it automatically. The normalisation here must stay identical to
lpd_setup_fingerprint() in lilypawdigital/inc/page-setup.php.
"""
import collections, glob, hashlib, html, re, subprocess

SLUGS = {'home': 'home', 'colocation': 'colocation', 'about': 'about-us',
         'work': 'our-work', 'contact': 'contact-us', 'getstarted': 'get-started'}


def fingerprint(content):
    content = content.replace('{{theme_uri}}', '{{T}}')
    content = re.sub(r'(?:https?://[^\s"\'<>]+?)?/wp-content/themes/[A-Za-z0-9_-]+', '{{T}}', content)
    content = re.sub(r'\s+rel="[^"]*"', '', content)
    content = re.sub(r'\s+', ' ', content).strip()
    return hashlib.md5(content.encode()).hexdigest()


known = collections.defaultdict(list)


def add(slug, content):
    value = fingerprint(content)
    if value not in known[slug]:
        known[slug].append(value)


def git(*args):
    return subprocess.check_output(('git',) + args).decode()


for commit in git('log', '--format=%H', '--reverse').split():
    for path in git('ls-tree', '-r', '--name-only', commit).split('\n'):
        if path.endswith('copy-all-page-content.html'):
            page = git('show', f'{commit}:{path}')
            for key, body in re.findall(r'<textarea id="ta-([a-z]+)"[^>]*>(.*?)</textarea>', page, re.S):
                if key in SLUGS:
                    add(SLUGS[key], html.unescape(body))
        match = re.match(r'.*/inc/pages/([a-z-]+)\.html$', path)
        if match and match.group(1) in SLUGS.values():
            add(match.group(1), git('show', f'{commit}:{path}'))

for path in glob.glob('lilypawdigital/inc/pages/*.html'):
    add(path.split('/')[-1][:-5], open(path).read())

out = """<?php
/**
 * Fingerprints of every version of the page content this theme has
 * shipped. Generated by tools/update-page-fingerprints.py - do not edit
 * by hand. A page whose content matches one of these has not been
 * edited, so the theme can safely bring it up to date.
 */

if ( ! defined( 'ABSPATH' ) ) exit;

return array(
"""
for slug in SLUGS.values():
    out += "\t'%s' => array(\n" % slug + ''.join("\t\t'%s',\n" % h for h in known[slug]) + "\t),\n"
out += ");\n"
open('lilypawdigital/inc/pages/known-fingerprints.php', 'w').write(out)
print({slug: len(values) for slug, values in known.items()})
